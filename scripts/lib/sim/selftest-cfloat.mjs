/**
 * selftest-cfloat.mjs —— cfloat.mjs 的用例表：[名字, () => 实际值, 期望]
 * 期望值都是 C 的 printf 的确定结果（对精确平局取偶；不是平局的按最近舍入）。
 */

import { fmtExp, fmtFixed, fmtGC } from '../lua/cfloat.mjs';
import { fmtG } from '../lua/value.mjs';

export function cfloatCases() {
  return [
    ['%.1f：0.25 是精确平局 → 0.2（JS toFixed 给 0.3）', () => fmtFixed(0.25, 1), '0.2'],
    ['%.1f：0.35 的 double 略小于 0.35 → 0.3', () => fmtFixed(0.35, 1), '0.3'],
    ['%.0f：0.5 → 0，1.5 → 2，2.5 → 2（平局取偶）', () => [fmtFixed(0.5, 0), fmtFixed(1.5, 0), fmtFixed(2.5, 0)].join(','), '0,2,2'],
    ['%.2f：0.125 → 0.12，0.375 → 0.38', () => `${fmtFixed(0.125, 2)},${fmtFixed(0.375, 2)}`, '0.12,0.38'],
    ['%.2f：2.675 的 double 是 2.67499999… → 2.67', () => fmtFixed(2.675, 2), '2.67'],
    ['%.3f / %.6f 普通值', () => `${fmtFixed(3.14159, 3)},${fmtFixed(1 / 3, 6)}`, '3.142,0.333333'],
    ['%.2f：1e21 按精确十进制展开', () => fmtFixed(1e21, 2), '1000000000000000000000.00'],
    ['%e：12345.678 → 1.234568e+04；0 → 0.000000e+00；1e-10 → 1.000e-10（3 位）', () => `${fmtExp(12345.678, 6)},${fmtExp(0, 6)},${fmtExp(1e-10, 3)}`, '1.234568e+04,0.000000e+00,1.000e-10'],
    ['%e：进位 —— 9.5 取 0 位小数 → 1e+01；9.9999995 实际略小于平局 → 9.999999e+00', () => `${fmtExp(9.5, 0)},${fmtExp(9.9999995, 6)}`, '1e+01,9.999999e+00'],
    ['%g：100000 → 100000；1000000 → 1e+06；0.0001 → 0.0001；0.00001 → 1e-05', () => [100000, 1000000, 0.0001, 0.00001].map((x) => fmtGC(x, 6)).join(','), '100000,1e+06,0.0001,1e-05'],
    ['%g：123456789 → 1.23457e+08；0.1 → 0.1；0.5 → 0.5', () => [123456789, 0.1, 0.5].map((x) => fmtGC(x, 6)).join(','), '1.23457e+08,0.1,0.5'],
    ['%.14g：0.1+0.2 → 0.3', () => fmtG(0.1 + 0.2), '0.3'],
    ['%.14g：123456789012345 是精确平局 → 1.2345678901234e+14（取偶）', () => fmtG(123456789012345), '1.2345678901234e+14'],
    ['%#g 保留末尾的 0', () => fmtGC(0.5, 6, true), '0.500000'],
  ];
}
